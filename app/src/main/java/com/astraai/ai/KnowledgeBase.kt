    /**
     * Поиск ответа по вопросу пользователя.
     */
    fun findAnswer(question: String): String? {

        val normalized = normalize(question)

        // Сначала ищем точное совпадение.
        knowledge[normalized]?.let { answer ->
            return answer
        }

        // Затем ищем вопрос, содержащий известную фразу.
        for ((key, answer) in knowledge) {
            if (normalized.contains(key)) {
                return answer
            }
        }

        return null
    }

    /**
     * Добавление нового знания в базу.
     */
    fun addKnowledge(
        question: String,
        answer: String
    ) {
        val normalized = normalize(question)
        knowledge[normalized] = answer
    }

    /**
     * Получение всей базы знаний.
     */
    fun getAllKnowledge(): Map<String, String> {
        return knowledge.toMap()
    }

    /**
     * Количество записей в базе.
     */
    fun size(): Int {
        return knowledge.size
    }

    /**
     * Очистка базы знаний.
     */
    fun clear() {
        knowledge.clear()
    }

    /**
     * Приведение вопроса к единому виду.
     */
    private fun normalize(text: String): String {
        return text
            .lowercase()
            .trim()
            .replace("ё", "е")
            .replace(Regex("\\s+"), " ")
            .removeSuffix("?")
            .trim()
    }
